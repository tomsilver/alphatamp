"""Phase 6 — Restock3D-v3 generator calibration run.

Generates many problems per stratum (no simulation) and histograms the difficulty statistics the
acceptance bands control — feasible-split ratio ``rho``, packing ``fill``, the near-threshold block
count, and the raw accept / reseed rate — so the ``strata_v3`` bands can be re-tuned *before* any
collection. Also confirms ``build_spec_v3`` resolves for a contiguous seed range (the collector's
skip rate) and probes floor-spawn reseed pressure.

Pure arithmetic (feasibility_v3 + generator_v3), so it is fast and deterministic. Writes a markdown
findings table to ``data/spectre/derived/restock3d_v3/generator_calibration.md`` and prints it.

Usage:
    python experiments/spectre/restock3d_v3_calibrate_generator.py [--n 400] [--raw 1500]
"""

from __future__ import annotations

import argparse
import statistics as stats
from pathlib import Path

from alphatamp.approaches.spectre.envs.restock3d import feasibility_v3 as F
from alphatamp.approaches.spectre.envs.restock3d import generator_v3 as G
from alphatamp.approaches.spectre.envs.restock3d import strata_v3 as S
from alphatamp.approaches.spectre.envs.restock3d.generator import (
    _EXCLUSION_RADIUS,
    _OBJECT_REGION_X,
    _OBJECT_REGION_Y,
    _SAMPLE_BUDGET,
    _Rng,
    _sample_positions,
)

_NEAR_LO, _NEAR_HI = (
    0.10,
    0.14,
)  # "near-threshold" full-height window around the 0.12 cutoff


def _pct(xs, p):
    if not xs:
        return float("nan")
    xs = sorted(xs)
    k = min(len(xs) - 1, int(p * len(xs)))
    return xs[k]


def _raw_probe(stratum: int, n_raw: int) -> dict:
    """Measure the RAW acceptance rate + accepted-instance distributions over ``n_raw``
    draws (one draw per seed, mirroring one attempt of build_spec_v3's reseed loop)."""
    p = S.params(stratum)
    n_accept = n_feasible = n_spawn_fail = 0
    rhos: list[float] = []
    fills: list[float] = []
    nears: list[int] = []
    for seed in range(n_raw):
        rng = _Rng(seed * 97 + stratum + 7)
        widths = [G._u(rng, F.WIDTH_MIN, F.WIDTH_MAX) for _ in range(p.n)]
        heights = G._sample_heights(rng, p.n, p.n_forced, p.n_near)
        blocks = [F.Block(f"o{i}", widths[i], heights[i]) for i in range(p.n)]
        nf, _tot, _rho = F.feasible_ratio(blocks)
        if nf >= 1:
            n_feasible += 1
        if G._accept(blocks, p):
            n_accept += 1
            _nf, _t, rho = F.feasible_ratio(blocks)
            rhos.append(rho)
            fills.append(F.min_fill_over_feasible(blocks))
            nears.append(sum(1 for h in heights if _NEAR_LO <= h <= _NEAR_HI))
            # floor-spawn reseed pressure at this n
            if (
                _sample_positions(
                    p.n,
                    rng,
                    _OBJECT_REGION_X,
                    _OBJECT_REGION_Y,
                    _EXCLUSION_RADIUS,
                    _SAMPLE_BUDGET,
                )
                is None
            ):
                n_spawn_fail += 1
    return {
        "stratum": stratum,
        "n": p.n,
        "raw": n_raw,
        "feasible_rate": n_feasible / n_raw,
        "accept_rate": n_accept / n_raw,
        "mean_reseeds": (n_raw / n_accept) if n_accept else float("inf"),
        "spawn_fail_rate": (n_spawn_fail / n_accept) if n_accept else float("nan"),
        "rho": (
            _pct(rhos, 0.10),
            stats.median(rhos) if rhos else float("nan"),
            _pct(rhos, 0.90),
        ),
        "fill": (
            _pct(fills, 0.10),
            stats.median(fills) if fills else float("nan"),
            _pct(fills, 0.90),
        ),
        "near": (
            min(nears) if nears else 0,
            stats.median(nears) if nears else 0,
            max(nears) if nears else 0,
        ),
    }


def _build_skip_rate(stratum: int, n: int) -> float:
    """Fraction of a contiguous seed range for which build_spec_v3 RAISES (collector
    skip)."""
    skipped = 0
    for seed in range(n):
        try:
            G.build_spec_v3(seed, stratum)
        except RuntimeError:
            skipped += 1
    return skipped / n


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--n", type=int, default=400, help="build_spec_v3 skip-rate seed range"
    )
    ap.add_argument(
        "--raw", type=int, default=1500, help="raw draws for the acceptance probe"
    )
    args = ap.parse_args()

    lines: list[str] = []
    lines.append("# Restock3D-v3 generator calibration\n")
    lines.append(
        f"_Generated by `experiments/spectre/restock3d_v3_calibrate_generator.py` "
        f"(raw={args.raw}, skip-range={args.n}). Pure arithmetic; no simulation._\n"
    )
    lines.append(
        "| stratum | n | crack | feasible% | accept% | ~reseeds | spawn-fail% | build-skip% "
        "| rho (p10/med/p90) | fill (p10/med/p90) | near (min/med/max) |"
    )
    lines.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for st in S.STRATA:
        r = _raw_probe(st, args.raw)
        skip = _build_skip_rate(st, args.n)
        p = S.params(st)
        lines.append(
            f"| {st} | {r['n']} | {p.require_crack} | {100*r['feasible_rate']:.0f}% | "
            f"{100*r['accept_rate']:.1f}% | {r['mean_reseeds']:.0f} | {100*r['spawn_fail_rate']:.1f}% | "
            f"{100*skip:.1f}% | {r['rho'][0]:.3f}/{r['rho'][1]:.3f}/{r['rho'][2]:.3f} | "
            f"{r['fill'][0]:.2f}/{r['fill'][1]:.2f}/{r['fill'][2]:.2f} | "
            f"{r['near'][0]}/{r['near'][1]}/{r['near'][2]} |"
        )
    lines.append(
        f"\nBands in `strata_v3`: FILL_BAND={S.FILL_BAND}; per-stratum rho_band = "
        + ", ".join(f"s{st}:{S.params(st).rho_band}" for st in S.STRATA)
        + ".\n"
    )
    report = "\n".join(lines)
    print(report)
    out = Path("data/spectre/derived/restock3d_v3/generator_calibration.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report)
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
